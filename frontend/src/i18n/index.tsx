interface I18nContextValue {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: string, vars?: Record<string, string | number>) => string
  dir: "ltr" | "rtl"
}

const I18nContext = createContext<I18nContextValue | null>(null)

function normalizeLocale(value: string): Locale | null {
  const lower = value.toLowerCase()
  if (lower.startsWith("zh")) return "zh-CN"
  for (const option of locales) {
    if (lower === option.code.toLowerCase() || lower.startsWith(option.code.toLowerCase() + "-")) return option.code
  }
  for (const option of locales) {
    if (lower.startsWith(option.code.split("-")[0])) return option.code
  }
  return null
}

function detectLocale(): Locale {
  const saved = localStorage.getItem("aq-locale")
  if (saved) {
    const normalized = normalizeLocale(saved)
    if (normalized) return normalized
  }
  for (const language of navigator.languages ?? [navigator.language]) {
    const normalized = normalizeLocale(language)
    if (normalized) return normalized
  }
  return "en"
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(detectLocale)

  const setLocale = (next: Locale) => {
    localStorage.setItem("aq-locale", next)
    setLocaleState(next)
  }

  useEffect(() => {
    const dir = locales.find((l) => l.code === locale)?.dir ?? "ltr"
    document.documentElement.lang = locale
    document.documentElement.dir = dir
  }, [locale])

  const value = useMemo<I18nContextValue>(() => {
    const t = (key: string, vars?: Record<string, string | number>) => {
      const template = messages[locale]?.[key] ?? key
      if (!vars) return template
      return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`))
    }
    return { locale, setLocale, t, dir: locales.find((l) => l.code === locale)?.dir ?? "ltr" }
  }, [locale])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider")
  return ctx
}
